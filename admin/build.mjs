// Bundles the pages in public/ into src/pages.gen.js as strings, so one small script can serve them.
// wrangler runs this before every deploy ([build] in wrangler.jsonc).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, 'public')
const walk = (d) => readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p] })
const pages = {}
for (const file of walk(root)) pages['/' + relative(root, file).split('\\').join('/')] = readFileSync(file, 'utf8')
writeFileSync(join(here, 'src/pages.gen.js'), `// Generated by build.mjs from public/. Don't edit.\nexport default ${JSON.stringify(pages, null, 0)}\n`)
console.log(`bundled ${Object.keys(pages).length} files`)
